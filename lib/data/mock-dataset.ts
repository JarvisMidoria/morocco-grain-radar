export interface MockDataset {
  ports: PortRecord[];
  vessels: VesselRecord[];
  voyages: VoyageRecord[];
  portCalls: PortCallRecord[];
  historicalRoutesByVessel: Record<string, string[]>;
}

const hours = (n: number) => n * 60 * 60 * 1000;
const days = (n: number) => n * 24 * 60 * 60 * 1000;

function getDepartureHoursAgo(vesselId: string, index: number) {
  const override = DEPARTURE_HOURS_OVERRIDES[vesselId];
  if (override) {
    return override;
  }

  // Keep a mix of very early, medium, and mature voyages for phase demonstration.
  return 20 + (index % 8) * 14;
}

function estimateArrivalDraft(departureDraft: number, vesselType: string, index: number) {
  const lower = vesselType.toLowerCase();
  if (!lower.includes("bulk") && !lower.includes("general cargo")) {
    return Math.max(2.8, Number((departureDraft - 0.4).toFixed(2)));
  }

  const delta = 1.4 + (index % 5) * 0.45;
  return Math.max(3.2, Number((departureDraft - delta).toFixed(2)));
}

function estimatePortStayHours(vesselType: string, index: number) {
  const lower = vesselType.toLowerCase();
  if (lower.includes("bulk")) {
    return 14 + (index % 4) * 6;
  }
  if (lower.includes("general cargo")) {
    return 10 + (index % 3) * 4;
  }
  return 4 + (index % 3) * 2;
}

export function buildMockDataset(referenceDate = new Date()): MockDataset {
  const vessels: VesselRecord[] = MOCK_VESSEL_SEEDS.map((seed) => ({
    id: seed.id,
    imo: seed.imo,
    mmsi: seed.mmsi,
    name: seed.name,
    vesselType: seed.vesselType,
    flag: seed.flag,
    deadweight: seed.deadweight,
    length: seed.length,
    width: seed.width,
    lastDraft: seed.lastDraft,
  }));

  const voyages: VoyageRecord[] = MOCK_VESSEL_SEEDS.map((seed, index) => {
    const destination = PORTS.find((port) => port.id === seed.destinationPortId);
    const etaDate = new Date(referenceDate.getTime() + hours(seed.etaHours));
    const departureHoursAgo = getDepartureHoursAgo(seed.id, index);
    const departureDetectedAt = new Date(referenceDate.getTime() - hours(departureHoursAgo));
    const lastSignalDate = new Date(referenceDate.getTime() - hours(Math.min(6, Math.max(1, departureHoursAgo / 3))));
    const destinationText = DESTINATION_TEXT_OVERRIDES[seed.id] ?? destination?.name ?? "Unknown";
    const departureDraft = seed.lastDraft;
    const arrivalDraft = estimateArrivalDraft(seed.lastDraft, seed.vesselType, index);
    const portStayHours = estimatePortStayHours(seed.vesselType, index);
    const loadingTerminalHint = LOADING_TERMINAL_BY_PORT_ID[seed.previousPortId] ?? null;
    const departureAt = departureDetectedAt.toISOString();
    const arrivalAt = new Date(departureDetectedAt.getTime() - hours(portStayHours)).toISOString();

    return {
      id: `${seed.id}-voyage`,
      vesselId: seed.id,
      currentLat: seed.currentLat,
      currentLon: seed.currentLon,
      speed: seed.speed,
      course: seed.course,
      heading: seed.heading,
      destinationText,
      destinationPortId: seed.destinationPortId,
      eta: etaDate.toISOString(),
      previousPortId: seed.previousPortId,
      departurePortId: seed.previousPortId,
      departureDetectedAt: departureDetectedAt.toISOString(),
      timeSinceDepartureHours: departureHoursAgo,
      originCountry: seed.originCountry,
      lastSignalAt: lastSignalDate.toISOString(),
      arrivalDraft,
      departureDraft,
      portStayHours,
      loadingTerminalHint,
      arrivalAt,
      departureAt,
    };
  });

  const portCalls: PortCallRecord[] = [];
  MOCK_VESSEL_SEEDS.forEach((seed, vesselIndex) => {
    seed.historicalRoutePortIds.forEach((portId, routeIndex) => {
      const arrivalTime = new Date(
        referenceDate.getTime() - days(24 - routeIndex * 4) - hours(vesselIndex % 9),
      );
      const departureTime = new Date(arrivalTime.getTime() + hours(16));

      portCalls.push({
        id: `pc-${seed.id}-${routeIndex}-arr`,
        vesselId: seed.id,
        portId,
        eventType: "ARRIVAL",
        eventTime: arrivalTime.toISOString(),
      });

      portCalls.push({
        id: `pc-${seed.id}-${routeIndex}-dep`,
        vesselId: seed.id,
        portId,
        eventType: "DEPARTURE",
        eventTime: departureTime.toISOString(),
      });
    });

    const previousDeparture = new Date(
      referenceDate.getTime() - hours(getDepartureHoursAgo(seed.id, vesselIndex)),
    );
    portCalls.push({
      id: `pc-${seed.id}-last-dep`,
      vesselId: seed.id,
      portId: seed.previousPortId,
      eventType: "DEPARTURE",
      eventTime: previousDeparture.toISOString(),
    });
  });

  const historicalRoutesByVessel = Object.fromEntries(
    MOCK_VESSEL_SEEDS.map((seed) => [seed.id, seed.historicalRoutePortIds]),
  );

  return {
    ports: PORTS,
    vessels,
    voyages,
    portCalls,
    historicalRoutesByVessel,
  };
}

export const MOCK_TRACKED_VESSEL_IDS = MOCK_VESSEL_SEEDS.map((seed) => seed.id);
